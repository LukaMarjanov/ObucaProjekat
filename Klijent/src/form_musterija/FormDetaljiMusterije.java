    private void popuniLokacije() {
        try {
            ArrayList<Lokacija> lokacije = ClientController.getInstance()
                    .getAllLokacija(new Lokacija(null, "", "", 0));

            cmbLokacija.removeAllItems();

            for (Lokacija lokacija : lokacije) {
                cmbLokacija.addItem(lokacija);
            }

        } catch (Exception ex) {
            Logger.getLogger(FormNovaMusterija.class.getName()).log(Level.SEVERE, null, ex);
        }
    }

