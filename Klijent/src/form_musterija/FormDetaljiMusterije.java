    private void btnObrisiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnObrisiActionPerformed

        int result = JOptionPane.showConfirmDialog(this, "Da li ste sigurni da zelite da "
                + "obrisete ovu musteriju?", "Konfirmacija", JOptionPane.YES_NO_OPTION);

        if (result == JOptionPane.NO_OPTION) {
            return;
        }

        if (result == JOptionPane.YES_OPTION) {
            try {
                ClientController.getInstance().deleteMusterija(m);
                FormPretragaMusterije fp = (FormPretragaMusterije) getParent();
                fp.refreshTable();
                Session.getInstance().getMf().popuniMusterije();
                JOptionPane.showMessageDialog(this, "Uspesno obrisana musterija.");
                this.dispose();
            } catch (Exception ex) {
                JOptionPane.showMessageDialog(this, "Ne mozete da obrisete ovu musteriju "
                        + "jer ima racune!",
                        "Obavestenje", JOptionPane.ERROR_MESSAGE);

            }
        }

    }//GEN-LAST:event_btnObrisiActionPerformed

    private void btnIzmeniActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIzmeniActionPerformed

        try {

            if (txtEmail.getText().isEmpty()
                    || txtTelefon.getText().isEmpty()) {
                JOptionPane.showMessageDialog(this, "Sva polja moraju biti popunjena!");
                return;
            }

            String email = txtEmail.getText();
            String telefon = txtTelefon.getText();
            Lokacija lokacija = (Lokacija) cmbLokacija.getSelectedItem();

            m.setEmail(email);
            m.setTelefon(telefon);
            m.setLokacija(lokacija);
            
            ClientController.getInstance().updateMusterija(m);
            FormPretragaMusterije fp = (FormPretragaMusterije) getParent();
            fp.refreshTable();
            Session.getInstance().getMf().popuniMusterije();
            JOptionPane.showMessageDialog(this, "Uspesno izmenjena musterija.");
            this.dispose();

        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage(),
                    "Greska", JOptionPane.ERROR_MESSAGE);
//            Logger.getLogger(FormDetaljiMusterije.class.getName()).log(Level.SEVERE, null, ex);
        }

    }//GEN-LAST:event_btnIzmeniActionPerformed


