    private void popuniObucu() {
        try {
            ArrayList<Obuca> listaObuca = ClientController.getInstance().getAllObuca(new Obuca(null, "", "", 0, 0));

            cmbObuca.removeAllItems();

            for (Obuca obuca : listaObuca) {
                cmbObuca.addItem(obuca);
            }
        } catch (Exception e) {
            e.printStackTrace();
        }
    }
