    private void txtKolicinaKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_txtKolicinaKeyReleased
        if (evt.getKeyChar() >= '0' && evt.getKeyChar() <= '9') {

            Obuca o = (Obuca) cmbObuca.getSelectedItem();
            int kolicina = Integer.parseInt(txtKolicina.getText());

            if (kolicina == 0) {
                txtKolicina.setText("");
                txtIznos.setText("");
                return;
            }

            txtIznos.setText(String.valueOf(o.getCena() * kolicina));

        } else {
            txtKolicina.setText("");
            txtIznos.setText("");
        }
    }//GEN-LAST:event_txtKolicinaKeyReleased

    private void cmbObucaItemStateChanged(java.awt.event.ItemEvent evt) {//GEN-FIRST:event_cmbObucaItemStateChanged
        if (cmbObuca.getSelectedItem() != null) {
            if (txtKolicina.getText().isEmpty()) {
                return;
            }

            Obuca o = (Obuca) cmbObuca.getSelectedItem();
            int kolicina = Integer.parseInt(txtKolicina.getText());

            if (kolicina == 0) {
                txtKolicina.setText("");
                txtIznos.setText("");
                return;
            }
            txtIznos.setText(String.valueOf(o.getCena() * kolicina));
        }
    }//GEN-LAST:event_cmbObucaItemStateChanged

    private void btnDodajActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDodajActionPerformed

        if (txtKolicina.getText().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Morate uneti kolicinu stavke!");
            return;
        }

        Obuca o = (Obuca) cmbObuca.getSelectedItem();
        int kolicina = Integer.parseInt(txtKolicina.getText());
        double iznos = Double.parseDouble(txtIznos.getText());

        StavkaRacuna sr = new StavkaRacuna(originalniRacun, -1, kolicina, o.getCena(), iznos, o);

        TableModelStavkeRacuna tr = (TableModelStavkeRacuna) tblStavke.getModel();
        tr.dodajStavku(sr);

        ukupanIznos = tr.vratiUkupanIznos();
        txtUkupanIznos.setText(String.valueOf(ukupanIznos) + "din");
    }//GEN-LAST:event_btnDodajActionPerformed

    private void btnObrisiActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnObrisiActionPerformed
        int row = tblStavke.getSelectedRow();

        if (row != -1) {
            TableModelStavkeRacuna tr = (TableModelStavkeRacuna) tblStavke.getModel();
            tr.obrisiStavkuRacuna(row);

            ukupanIznos = tr.vratiUkupanIznos();
            txtUkupanIznos.setText(String.valueOf(ukupanIznos) + "din");
        }


    }//GEN-LAST:event_btnObrisiActionPerformed

    private void btnIzmeniActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIzmeniActionPerformed
        try {
            TableModelStavkeRacuna tm = (TableModelStavkeRacuna) tblStavke.getModel();

            originalniRacun.setDatumVreme(new Date());
            originalniRacun.setStatus("Aktivan");
            originalniRacun.setUkupanIznos(ukupanIznos);
            originalniRacun.setStavkeRacuna(tm.getLista());

            ClientController.getInstance().updateRacun(originalniRacun);
            FormPretragaRacuna fp = (FormPretragaRacuna) getParent();
            fp.refreshTable();
            JOptionPane.showMessageDialog(this, "Uspesno izmenjen racun");
            this.dispose();
        } catch (Exception ex) {
            JOptionPane.showMessageDialog(this, ex.getMessage());
        }
    }//GEN-LAST:event_btnIzmeniActionPerformed

    private void btnStornirajActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnStornirajActionPerformed
        int result = JOptionPane.showConfirmDialog(this, "Da li ste sigurni da zelite da "
                + "stornirate ovaj racun?", "Konfirmacija", JOptionPane.YES_NO_OPTION);

        if (result == JOptionPane.NO_OPTION) {
            return;
        }

        if (result == JOptionPane.YES_OPTION) {
            try {

                ArrayList<StavkaRacuna> stornoStavke = new ArrayList<>();

                for (StavkaRacuna sr : originalniRacun.getStavkeRacuna()) {
                    stornoStavke.add(new StavkaRacuna(null, sr.getRb(), sr.getKolicina() * -1,
                            sr.getCena(), sr.getIznos() * -1, sr.getObuca()));
                }

                Racun stornoRacun = new Racun(null, new Date(), "STORNO", originalniRacun.getRacunID(),
                        originalniRacun.getUkupanIznos() * -1, Session.getInstance().getUlogovani(),
                        originalniRacun.getMusterija(), stornoStavke);

                ClientController.getInstance().cancelRacun(stornoRacun);
                originalniRacun.setStatus("STORNIRAN");
                ClientController.getInstance().updateRacun(originalniRacun);
                FormPretragaRacuna fp = (FormPretragaRacuna) getParent();
                fp.refreshTable();
                JOptionPane.showMessageDialog(this, "Uspesno storniran racun.");
                this.dispose();
            } catch (Exception ex) {
                Logger.getLogger(FormDetaljiRacuna.class.getName()).log(Level.SEVERE, null, ex);
            }
        }
    }//GEN-LAST:event_btnStornirajActionPerformed


